const { chromium } = require("playwright");
const { pathToFileURL } = require("url");
const path = require("path");
const assert = require("assert");
const fs = require("fs");

(async () => {
  fs.mkdirSync("_shots", { recursive: true });
  const browser = await chromium.launch({
    headless: true,
    channel: "chrome",
    args: ["--allow-file-access-from-files"],
  });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on("console", (message) => { if (message.type() === "error") errors.push(`console:${message.text()}`); });
  page.on("pageerror", (error) => errors.push(`page:${error.message}`));
  await page.goto(pathToFileURL(path.resolve("index.html")).href);
  console.log("OPEN", await page.title(), (await page.locator("#todayMeta").textContent()).slice(0, 80));
  await page.locator("#studyDate").fill("2026-09-19");
  await page.locator("#studyDate").dispatchEvent("change");
  await page.locator("#startLearning").click();
  console.log("START", await page.locator("#practice").isVisible(), await page.locator("#stepNav").isVisible(), await page.locator("#practice h2").textContent());
  assert.equal(await page.locator(".lesson-line").count(), 4);
  assert.equal(await page.locator(".lesson-line .lesson-translation").count(), 4);
  assert.equal(await page.locator(".lesson-line").first().locator(".lesson-translation").textContent(), "我在办公室工作。");
  assert.equal(await page.locator("#practice summary").count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth), false);
  await page.locator(".lesson-text").scrollIntoViewIfNeeded();
  await page.screenshot({ path: "_shots/warmup-mobile.png", fullPage: false });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('[data-step="1"]').click();
  const expectedWord = await page.locator('.word-stage [data-audio][data-accent="US"]').getAttribute("data-audio");
  assert.equal(await page.locator(".word-label").count(), 0);
  assert.equal(await page.locator(".word-stage .phonetic").count(), 0);
  console.log("WORD", await page.locator(".word-listening").textContent(), await page.locator(".word-progress").textContent());
  await page.locator("[data-toggle-meaning]").click();
  assert.equal(await page.locator("details.example").count(), 0);
  assert.equal(await page.locator(".example-line [data-audio]").count(), 0);
  assert.equal(await page.locator(".word-label").count(), 0);
  console.log("MEANING", (await page.locator(".word-meaning").textContent()).slice(0, 30));
  await page.locator("#spellInput").fill("wrong");
  await page.locator("#spellForm").locator("button").click();
  assert.equal(await page.locator(".word-label").count(), 0);
  assert.equal(await page.locator("details.example").count(), 0);
  assert.equal(await page.locator("#practice .usage-notes").count(), 0);
  assert.equal(await page.locator("#spellForm button").textContent(), "检查");
  assert(!(await page.locator(".spell-feedback").textContent()).includes(expectedWord));
  console.log("WRONG", await page.locator(".spell-feedback").textContent());
  await page.locator("#spellInput").fill(expectedWord);
  await page.locator("#spellForm button").click();
  assert.equal(await page.locator(".word-label").textContent(), expectedWord);
  assert.equal(await page.locator("details.example").count(), 1);
  assert((await page.locator("#practice .usage-notes").textContent()).includes("a job"));
  assert.equal(await page.locator(".example-line [data-audio]").count(), 1);
  await page.locator("#ownSentence").fill("I work at home.");
  console.log("CORRECT", await page.locator(".spell-feedback").textContent(), await page.locator("#spellForm button").textContent());
  await page.locator("#spellForm button").click();
  assert.equal(await page.locator(".word-label").count(), 0);
  console.log("NEXT", await page.locator(".word-listening").textContent());
  await page.locator('[data-step="2"]').click();
  assert((await page.locator("#practice [data-speak]").count()) >= 4);
  await page.locator('[data-step="3"]').click();
  assert((await page.locator("#summaryText").inputValue()).includes("I work at home."));
  await page.locator("#studyDate").fill("2026-09-26");
  await page.locator("#studyDate").dispatchEvent("change");
  console.log("SAT", await page.locator("#todayMeta").textContent(), await page.locator("#wordCountLabel").textContent());
  await page.locator("[data-view=resources]").click();
  console.log("RESOURCES", await page.locator("#view-resources").isVisible(), (await page.locator("#vocabStats").textContent()).slice(0, 55));
  await page.locator("#wordSearch").fill("notes");
  await page.locator("#searchWord").click();
  console.log("SEARCH", await page.locator(".search-results article h3").first().textContent(), (await page.locator(".search-results article p").first().textContent()).slice(0, 28));
  await page.locator("[data-view=mistakes]").click();
  assert((await page.locator("#deckStats").textContent()).includes("1 个曾输错或忘记的词"));
  assert.equal(await page.locator("#mistakeList article > .overline h3").first().textContent(), expectedWord);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  console.log("MOBILE", await page.evaluate(() => ({ scrollWidth: document.documentElement.scrollWidth, clientWidth: document.documentElement.clientWidth, overflow: document.documentElement.scrollWidth > document.documentElement.clientWidth })));
  console.log("ERRORS", JSON.stringify(errors));
  await page.screenshot({ path: "_shots/new-mobile.png", fullPage: false });
  await page.locator("#reviewMistakes").click();
  assert.equal(await page.locator("[data-flash-reveal]").count(), 1);
  assert.equal(await page.locator('[data-step="1"][aria-current="step"]').count(), 1);
  await page.evaluate(() => localStorage.setItem("little-english-progress-v1", JSON.stringify({
    cards: { work: { stage: 0, due: "2026-01-01", last: "2025-12-31", hits: 1, misses: 0 } }, days: {},
  })));
  await page.goto(pathToFileURL(path.resolve("index.html")).href);
  await page.locator("#studyDate").fill("2026-09-20");
  await page.locator("#studyDate").dispatchEvent("change");
  assert((await page.locator("#reviewNote").textContent()).includes("1 张到期闪卡"));
  await page.locator("#startLearning").click();
  await page.locator('[data-step="1"]').click();
  assert.equal(await page.locator("[data-flash-reveal]").count(), 1);
  assert.equal(await page.locator(".flash-card .word-label").count(), 0);
  await page.locator("[data-flash-reveal]").click();
  assert.equal(await page.locator(".flash-card .word-label").textContent(), "work");
  assert.equal(await page.locator(".flash-card .example-line [data-audio]").count(), 1);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth), false);
  await page.locator(".flash-card").scrollIntoViewIfNeeded();
  await page.screenshot({ path: "_shots/flashcard-mobile.png", fullPage: false });
  await page.locator('[data-flash-rating="remembered"]').click();
  assert.equal(await page.locator("#spellForm").count(), 1);
  assert.equal(await page.locator(".flash-card").count(), 0);
  const scheduled = await page.evaluate(() => JSON.parse(localStorage.getItem("little-english-progress-v1")).cards.work);
  assert.equal(scheduled.stage, 1);
  await page.reload();
  await page.locator("#studyDate").fill("2026-09-20");
  await page.locator("#studyDate").dispatchEvent("change");
  assert.equal(await page.locator('[data-step="1"][aria-current="step"]').count(), 1);
  console.log("FLASH", scheduled.due, scheduled.stage);
  await browser.close();
})().catch((error) => { console.error(error); process.exitCode = 1; });
